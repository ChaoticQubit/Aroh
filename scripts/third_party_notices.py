"""Writes THIRD_PARTY_NOTICES.md for the Aroh app from `cargo metadata`.

Walks the normal (shipped) dependency graph of the `aroh` app crate, keeps every registry
package, and prints its licence expression, source link and the licence files it carries.
Run from the repository root: `python3 scripts/third_party_notices.py > THIRD_PARTY_NOTICES.md`.
"""

import json
import pathlib
import subprocess
import sys

APP = "aroh"
FILE_PREFIXES = ("license", "licence", "copying", "notice", "copyright")
WEAK_COPYLEFT = ("MPL-2.0",)
PLATFORMS = ("--filter-platform", "aarch64-apple-ios", "--filter-platform", "aarch64-apple-darwin")


def metadata():
    """Runs `cargo metadata --locked` and returns the parsed JSON document."""
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", *PLATFORMS],
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(out.stdout)


def shipped(meta):
    """Returns the packages the app links: its normal dependencies, transitively, from registries.

    Input: the `cargo metadata` document. Output: package dicts sorted by name and version.
    """
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    roots = [p["id"] for p in meta["packages"] if p["name"] == APP and p["source"] is None]
    assert len(roots) == 1, f"expected one {APP} package, found {len(roots)}"
    seen = set()
    stack = list(roots)
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    third = [packages[i] for i in seen if packages[i]["source"] is not None]
    assert third, "the app has no third-party dependencies, cargo metadata looks wrong"
    return sorted(third, key=lambda p: (p["name"], p["version"]))


def licence_texts(package):
    """Returns (file name, text) for each licence or notice file in the package directory."""
    root = pathlib.Path(package["manifest_path"]).parent
    found = []
    for path in sorted(root.iterdir()):
        if path.is_file() and path.name.lower().startswith(FILE_PREFIXES):
            found.append((path.name, path.read_text(encoding="utf-8", errors="replace").strip()))
    if package.get("license_file"):
        extra = root / package["license_file"]
        if extra.is_file() and extra.name not in {n for n, _ in found}:
            found.append((extra.name, extra.read_text(encoding="utf-8", errors="replace").strip()))
    return found


def source_link(package):
    """Returns where a reader gets the package's source: its repository, else its crates.io page."""
    return package.get("repository") or f"https://crates.io/crates/{package['name']}/{package['version']}"


def render(packages):
    """Renders the notices document as Markdown and returns it as one string."""
    lines = [
        "# Third-party notices",
        "",
        "The Aroh app links the Rust crates below. Each keeps its own licence; every licence text",
        "the crates ship is printed once at the end. Generated by `scripts/third_party_notices.py` from",
        "`cargo metadata`; do not edit by hand.",
        "",
        "## Weak copyleft (MPL-2.0)",
        "",
        "These crates are used unmodified. Their source is available at the link given, and the",
        "MPL-2.0 text is at https://mozilla.org/MPL/2.0/.",
        "",
    ]
    for p in packages:
        expr = p.get("license") or "see licence files"
        if any(w in expr for w in WEAK_COPYLEFT):
            lines.append(f"- `{p['name']}` {p['version']}: {expr}, source {source_link(p)}")
    texts = {}
    lines += ["", "## Crates", ""]
    for p in packages:
        refs = []
        for name, text in licence_texts(p):
            refs.append(f"[{name}](#text-{texts.setdefault(text, len(texts) + 1)})")
        files = ", ".join(refs) if refs else "none shipped"
        lines.append(f"- `{p['name']}` {p['version']}: {p.get('license') or 'see licence files'}; source {source_link(p)}; texts {files}")
    lines += ["", "## Licence texts", ""]
    for text, number in texts.items():
        lines += [f'<a id="text-{number}"></a>', "", f"### Text {number}", "", "```text", text.replace("```", "'''"), "```", ""]
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    sys.stdout.write(render(shipped(metadata())))
